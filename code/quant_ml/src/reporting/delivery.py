import logging
import mimetypes
import os
import re
import smtplib
import ssl
from dataclasses import dataclass
from email.message import EmailMessage
from typing import Any, Callable, Dict, List, Mapping, Optional, Sequence

logger = logging.getLogger(__name__)

ADDRESS_PATTERN = re.compile(
    r"^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$"
)
MAX_RECIPIENTS = 50
MAX_ATTACHMENT_BYTES = 15 * 1024 * 1024
TRUE_VALUES = {"1", "true", "yes", "on"}


class DeliveryError(RuntimeError):
    pass


def validate_recipients(recipients: Sequence[str]) -> List[str]:
    if not isinstance(recipients, (list, tuple)):
        raise ValueError("recipients must be a list of email addresses")
    cleaned: List[str] = []
    for address in recipients:
        if not isinstance(address, str):
            raise ValueError("recipients must be strings")
        candidate = address.strip()
        if len(candidate) > 254 or not ADDRESS_PATTERN.match(candidate):
            raise ValueError(f"Invalid email address: {address!r}")
        if candidate.lower() not in [c.lower() for c in cleaned]:
            cleaned.append(candidate)
    if len(cleaned) > MAX_RECIPIENTS:
        raise ValueError(f"At most {MAX_RECIPIENTS} recipients are allowed")
    return cleaned


@dataclass(frozen=True)
class SmtpSettings:
    host: str
    sender: str
    port: int = 587
    username: Optional[str] = None
    password: Optional[str] = None
    use_tls: bool = True
    use_ssl: bool = False
    timeout: float = 30.0

    @classmethod
    def from_environment(
        cls, environment: Optional[Mapping[str, str]] = None
    ) -> Optional["SmtpSettings"]:
        env = os.environ if environment is None else environment
        host = env.get("QUANT_ML_SMTP_HOST", "").strip()
        sender = env.get("QUANT_ML_SMTP_SENDER", "").strip()
        if not host or not sender:
            return None
        if not ADDRESS_PATTERN.match(sender):
            raise ValueError("QUANT_ML_SMTP_SENDER is not a valid email address")
        use_ssl = env.get("QUANT_ML_SMTP_SSL", "false").strip().lower() in TRUE_VALUES
        use_tls = env.get("QUANT_ML_SMTP_TLS", "true").strip().lower() in TRUE_VALUES
        default_port = 465 if use_ssl else 587
        try:
            port = int(env.get("QUANT_ML_SMTP_PORT", default_port))
            timeout = float(env.get("QUANT_ML_SMTP_TIMEOUT", 30))
        except ValueError as error:
            raise ValueError(
                "QUANT_ML_SMTP_PORT and QUANT_ML_SMTP_TIMEOUT must be numbers"
            ) from error
        return cls(
            host=host,
            sender=sender,
            port=port,
            username=env.get("QUANT_ML_SMTP_USER") or None,
            password=env.get("QUANT_ML_SMTP_PASSWORD") or None,
            use_tls=use_tls and not use_ssl,
            use_ssl=use_ssl,
            timeout=timeout,
        )


class EmailDelivery:
    def __init__(
        self,
        settings: SmtpSettings,
        smtp_factory: Optional[Callable[..., Any]] = None,
        max_attachment_bytes: int = MAX_ATTACHMENT_BYTES,
    ) -> None:
        self.settings = settings
        self.smtp_factory = smtp_factory
        self.max_attachment_bytes = max_attachment_bytes

    @classmethod
    def from_environment(
        cls, environment: Optional[Mapping[str, str]] = None
    ) -> Optional["EmailDelivery"]:
        settings = SmtpSettings.from_environment(environment)
        return cls(settings) if settings else None

    def build_message(
        self, report_path: str, recipients: Sequence[str]
    ) -> EmailMessage:
        if not os.path.isfile(report_path):
            raise DeliveryError(
                f"Report file not found: {os.path.basename(report_path)}"
            )
        if os.path.getsize(report_path) > self.max_attachment_bytes:
            raise DeliveryError("Report is too large to attach")
        filename = os.path.basename(report_path)
        message = EmailMessage()
        message["From"] = self.settings.sender
        message["To"] = ", ".join(recipients)
        message["Subject"] = f"Scheduled report: {filename}"
        message.set_content(
            f"The report {filename} generated by RiskOptimizer is attached."
        )
        mime, _ = mimetypes.guess_type(filename)
        main, _, sub = (mime or "application/octet-stream").partition("/")
        with open(report_path, "rb") as handle:
            message.add_attachment(
                handle.read(), maintype=main, subtype=sub, filename=filename
            )
        return message

    def open_connection(self) -> Any:
        if self.smtp_factory is not None:
            return self.smtp_factory(
                self.settings.host, self.settings.port, timeout=self.settings.timeout
            )
        if self.settings.use_ssl:
            return smtplib.SMTP_SSL(
                self.settings.host,
                self.settings.port,
                timeout=self.settings.timeout,
                context=ssl.create_default_context(),
            )
        return smtplib.SMTP(
            self.settings.host, self.settings.port, timeout=self.settings.timeout
        )

    def __call__(self, report_path: str, recipients: Sequence[str]) -> bool:
        addresses = validate_recipients(list(recipients))
        if not addresses:
            raise DeliveryError("No recipients provided")
        message = self.build_message(report_path, addresses)
        try:
            with self.open_connection() as connection:
                if self.settings.use_tls:
                    connection.starttls(context=ssl.create_default_context())
                if self.settings.username:
                    connection.login(
                        self.settings.username, self.settings.password or ""
                    )
                refused: Dict[str, Any] = connection.send_message(
                    message, to_addrs=addresses
                )
        except (smtplib.SMTPException, OSError) as error:
            logger.error("Email delivery failed: %s", error)
            raise DeliveryError(f"SMTP delivery failed: {error}") from error
        if refused:
            raise DeliveryError(f"Recipients refused by server: {sorted(refused)}")
        return True
